// Rewrite the cross-runtime report block in the top-level README between the
// markers `<!-- tests:begin -->` and `<!-- tests:end -->`. Idempotent: running
// it with an unchanged report leaves the file byte-identical.
//
// Usage: node scripts/tests_readme.mjs [reportPath] [readmePath]

import { readFileSync, writeFileSync } from "node:fs";
import {
  byCategory,
  fmtRate,
  loadReport,
  rollupSummary,
} from "./tests_report_lib.mjs";

const reportPath = process.argv[2] ?? ".github/tests_report.json";
const readmePath = process.argv[3] ?? "README.md";

const BEGIN = "<!-- tests:begin -->";
const END = "<!-- tests:end -->";

const { results } = loadReport(reportPath);
// Recompute the rollup from the per-fixture results so column names are
// consistent (the shell summary uses `errors`, this uses `zun_error`).
const summary = rollupSummary(results);
const cats = byCategory(results);
const today = new Date().toISOString().slice(0, 10);

const rate = summary.share === "n/a" ? "n/a" : `${summary.share}%`;
const lines = [];
lines.push(BEGIN);
lines.push(
  `**Cross-runtime conformance: ${rate}** ` +
    `(${summary.pass} / ${summary.reachable} reachable fixtures match Bun and Node) · ` +
    `updated ${today}`,
);
lines.push("");
lines.push(
  "| Category | Pass | Diverge | Error | Skipped | Rate |",
);
lines.push("| --- | ---: | ---: | ---: | ---: | ---: |");
for (const c of cats) {
  lines.push(
    `| \`${c.category}\` | ${c.pass} | ${c.zun_diverge} | ${c.zun_error} | ${c.skipped} | ${fmtRate(c.rate)} |`,
  );
}
const totalRate = summary.share === "n/a" ? "n/a" : `${summary.share}%`;
lines.push(
  `| **Total** | **${summary.pass}** | **${summary.zun_diverge}** | **${summary.zun_error}** | ` +
    `**${summary.bun_node_diverge + summary.upstream_defect + summary.rejected}** | **${totalRate}** |`,
);
lines.push("");
lines.push(
  "<sub>Diverge = Zun output differs from Bun/Node · Error = Zun crashed/timed out · " +
    "Skipped = Bun≠Node, upstream defect, or non-portable fixture (excluded from the rate). " +
    "Generated by CI from `scripts/tests_check.sh`.</sub>",
);
lines.push(END);

const block = lines.join("\n");

let readme = readFileSync(readmePath, "utf8");
const start = readme.indexOf(BEGIN);
const stop = readme.indexOf(END);
if (start === -1 || stop === -1 || stop < start) {
  throw new Error(
    `README markers not found or malformed: expected "${BEGIN}" ... "${END}"`,
  );
}
const updated =
  readme.slice(0, start) + block + readme.slice(stop + END.length);

if (updated !== readme) {
  writeFileSync(readmePath, updated);
  console.log(`README updated: ${rate} conformance`);
} else {
  console.log("README unchanged");
}
