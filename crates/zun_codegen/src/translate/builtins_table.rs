//! The builtin-descriptor table: maps a native builtin name to the imported
//! JIT helper that lowers it, its arity, its argument machine type, and its
//! result kind/type. This is pure data lifted verbatim out of the `CallBuiltin`
//! arm of `translate/mod.rs` (each former multi-line tuple arm collapsed to one
//! line, no values changed).
//!
//! It is NOT an opcode table and NOT a second source of opcode knowledge: it
//! reads the `zun_natives::by_id` name the dispatcher already resolved. There is
//! one logical lookup, [`builtin_desc`]; it is split into two category helpers
//! only to keep this file within the line budget.

use super::*;

/// `(symbol, arity, argument machine type, result kind, result machine type)`.
pub(crate) type BuiltinDesc = (&'static str, usize, Type, JitKind, Type);

/// Resolve a builtin name to its descriptor, or `None` for an unsupported one.
pub(crate) fn builtin_desc(name: Option<&str>) -> Option<BuiltinDesc> {
    builtin_desc_scalar(name).or_else(|| builtin_desc_binary(name))
}

